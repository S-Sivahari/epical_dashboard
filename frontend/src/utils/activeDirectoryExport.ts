const COMPANY_NAME = 'EPICAL LAYOUTS PVT LTD'
const REPORT_TITLE = 'Employee Active Directory Report'
const BRAND_GREEN: [number, number, number] = [6, 192, 51]
const BRAND_GREEN_ARGB = 'FF06C033'
const MARGIN_X = 40
const LOGO_MAX_WIDTH = 64
const LOGO_GAP = 14

export type ActiveDirectoryExportOptions = {
  generatedBy?: string
  filters?: Record<string, string | undefined>
}

function formatReportDate(d: Date): string {
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  return `${String(d.getDate()).padStart(2, '0')}-${months[d.getMonth()]}-${d.getFullYear()}`
}

function formatReportTime(d: Date): string {
  let hours = d.getHours()
  const minutes = String(d.getMinutes()).padStart(2, '0')
  const ampm = hours >= 12 ? 'PM' : 'AM'
  hours = hours % 12
  hours = hours ? hours : 12
  return `${String(hours).padStart(2, '0')}:${minutes} ${ampm}`
}

function formatCellDate(value: unknown): string {
  if (!value) return '—'
  const date = new Date(String(value))
  if (Number.isNaN(date.getTime())) return String(value)
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  return `${String(date.getDate()).padStart(2, '0')}-${months[date.getMonth()]}-${date.getFullYear()}`
}

function buildFilterString(filters?: Record<string, string | undefined>): string {
  if (!filters) return 'None'
  const parts: string[] = []
  Object.entries(filters).forEach(([key, val]) => {
    if (val && val !== 'all' && val !== '') {
      let label = key
      if (key === 'employeeId') label = 'Employee ID'
      else if (key === 'employmentType') label = 'Type'
      else label = key.charAt(0).toUpperCase() + key.slice(1)
      parts.push(`${label} = ${val}`)
    }
  })
  return parts.length > 0 ? parts.join(' | ') : 'None'
}

function mapRowToCells(row: EmployeeExportRow): string[] {
  return ACTIVE_DIRECTORY_EXPORT_HEADERS.map((h) => {
    let value: unknown = row[h.key as string]
    if (h.key === 'joinedAt') {
      value = formatCellDate(value)
    }
    return value === null || value === undefined || value === '' ? '—' : String(value)
  })
}

/** Relative weights per Active Directory column — scaled to full printable width. */
const PDF_COLUMN_WEIGHTS = [1.15, 1, 1, 1.55, 1.55, 0.9, 0.95, 0.9] as const
const PDF_COLUMN_HALIGN: ('left' | 'center')[] = [
  'left',
  'left',
  'left',
  'left',
  'left',
  'center',
  'center',
  'center',
]

function buildPdfColumnStyles(pageWidth: number) {
  const tableWidth = pageWidth - MARGIN_X * 2
  const totalWeight = PDF_COLUMN_WEIGHTS.reduce((sum, w) => sum + w, 0)
  return PDF_COLUMN_WEIGHTS.reduce(
    (acc, weight, idx) => {
      acc[idx] = {
        cellWidth: (tableWidth * weight) / totalWeight,
        halign: PDF_COLUMN_HALIGN[idx],
      }
      return acc
    },
    {} as Record<number, { cellWidth: number; halign: 'left' | 'center' }>,
  )
}

function drawPdfHeader(
  doc: jsPDF,
  pageWidth: number,
  meta: { genDate: string; genTime: string; genBy: string; filterString: string },
  logo: Awaited<ReturnType<typeof fetchExportLogo>>,
): number {
  const topY = 28
  let textX = MARGIN_X
  let blockBottom = topY + 20

  if (logo) {
    const { width: lw, height: lh } = scaleExportLogo(logo.width, logo.height, LOGO_MAX_WIDTH)
    const format = EXPORT_LOGO_PATH.endsWith('.png') ? 'PNG' : 'JPEG'
    doc.addImage(logo.dataUrl, format, MARGIN_X, topY, lw, lh)
    textX = MARGIN_X + lw + LOGO_GAP
    blockBottom = Math.max(blockBottom, topY + lh)
  }

  const companyY = topY + 14
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  drawEpicalBrandedText(doc, { before: 'EP', after: 'AL LAYOUTS PVT LTD' }, textX, companyY, 'left', pageWidth, 'bold')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.setTextColor(15, 23, 42)
  const reportY = companyY + 18
  doc.text(REPORT_TITLE, textX, reportY)
  blockBottom = Math.max(blockBottom, reportY + 6)

  let y = blockBottom + 12
  doc.setDrawColor(226, 232, 240)
  doc.setLineWidth(0.75)
  doc.line(MARGIN_X, y, pageWidth - MARGIN_X, y)
  y += 16

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(71, 85, 105)
  doc.text(`Generated Date : ${meta.genDate}`, MARGIN_X, y)
  doc.text(`Generated Time : ${meta.genTime}`, pageWidth / 2, y, { align: 'center' })
  doc.text(`Generated By : ${meta.genBy}`, pageWidth - MARGIN_X, y, { align: 'right' })
  y += 18

  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 41, 59)
  doc.text('Applied Filters: ', MARGIN_X, y)
  const labelW = doc.getTextWidth('Applied Filters: ')
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(100, 116, 139)
  doc.text(meta.filterString, MARGIN_X + labelW, y)
  y += 12

  doc.line(MARGIN_X, y, pageWidth - MARGIN_X, y)
  return y + 10
}

function drawPdfFooters(doc: jsPDF, genDate: string, genTime: string) {
  const pageWidth = doc.internal.pageSize.width
  const pageHeight = doc.internal.pageSize.height
  const totalPages = doc.getNumberOfPages()

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    const lineY = pageHeight - 42
    doc.setDrawColor(226, 232, 240)
    doc.setLineWidth(0.75)
    doc.line(MARGIN_X, lineY, pageWidth - MARGIN_X, lineY)

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(8)
    doc.setTextColor(30, 41, 59)
    doc.text(`${COMPANY_NAME} – Confidential Document`, MARGIN_X, pageHeight - 28)

    doc.setFont('helvetica', 'normal')
    doc.setTextColor(100, 116, 139)
    doc.text(
      `System Generated Report | Generated on ${genDate} ${genTime} | Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 16,
      { align: 'center' },
    )
  }
}

export async function exportActiveDirectoryPdf(
  data: EmployeeExportRow[],
  filename: string,
  options?: ActiveDirectoryExportOptions,
) {
  if (!data.length) return

  const logo = await fetchExportLogo()
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' })
  const pageWidth = doc.internal.pageSize.width
  const now = new Date()
  const meta = {
    genDate: formatReportDate(now),
    genTime: formatReportTime(now),
    genBy: options?.generatedBy || 'Admin',
    filterString: buildFilterString(options?.filters),
  }

  const tableStartY = drawPdfHeader(doc, pageWidth, meta, logo)
  const tableWidth = pageWidth - MARGIN_X * 2
  const head = [ACTIVE_DIRECTORY_EXPORT_HEADERS.map((h) => h.label)]
  const body = data.map((row) => mapRowToCells(row))

  autoTable(doc, {
    head,
    body,
    startY: tableStartY,
    tableWidth,
    margin: { left: MARGIN_X, right: MARGIN_X, top: tableStartY, bottom: 52 },
    styles: {
      fontSize: 8,
      cellPadding: { top: 5, right: 5, bottom: 5, left: 5 },
      valign: 'middle',
      overflow: 'linebreak',
      lineColor: [226, 232, 240],
      lineWidth: 0.4,
      textColor: [30, 41, 59],
    },
    headStyles: {
      fillColor: BRAND_GREEN,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      halign: 'center',
      valign: 'middle',
    },
    alternateRowStyles: {
      fillColor: [240, 253, 244],
    },
    columnStyles: buildPdfColumnStyles(pageWidth),
    showHead: 'everyPage',
  })

  drawPdfFooters(doc, meta.genDate, meta.genTime)
  doc.save(`${filename}.pdf`)
}

const EXCEL_COL_WIDTHS: Partial<Record<string, number>> = {
  employeeId: 16,
  firstName: 14,
  lastName: 14,
  personalEmail: 32,
  email: 32,
  employmentType: 14,
  joinedAt: 14,
  status: 12,
}

export async function exportActiveDirectoryExcel(
  data: EmployeeExportRow[],
  filename: string,
  options?: ActiveDirectoryExportOptions,
) {
  if (!data.length) return

  const now = new Date()
  const genDate = formatReportDate(now)
  const genTime = formatReportTime(now)
  const genBy = options?.generatedBy || 'Admin'
  const filterString = buildFilterString(options?.filters)
  const colCount = ACTIVE_DIRECTORY_EXPORT_HEADERS.length

  const workbook = new ExcelJS.Workbook()
  workbook.creator = COMPANY_NAME
  const sheet = workbook.addWorksheet('Active Directory', {
    views: [{ showGridLines: true }],
  })

  const borderThin = {
    top: { style: 'thin' as const, color: { argb: 'FFE5E7EB' } },
    bottom: { style: 'thin' as const, color: { argb: 'FFE5E7EB' } },
    left: { style: 'thin' as const, color: { argb: 'FFE5E7EB' } },
    right: { style: 'thin' as const, color: { argb: 'FFE5E7EB' } },
  }

  let row = 1

  sheet.mergeCells(row, 1, row, colCount)
  const titleCell = sheet.getCell(row, 1)
  titleCell.value = COMPANY_NAME
  titleCell.font = { name: 'Segoe UI', size: 14, bold: true, color: { argb: 'FFFFFFFF' } }
  titleCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_GREEN_ARGB } }
  titleCell.alignment = { horizontal: 'center', vertical: 'middle' }
  sheet.getRow(row).height = 28
  row++

  sheet.mergeCells(row, 1, row, colCount)
  const subtitleCell = sheet.getCell(row, 1)
  subtitleCell.value = REPORT_TITLE
  subtitleCell.font = { name: 'Segoe UI', size: 11, bold: true, color: { argb: 'FF1E293B' } }
  subtitleCell.alignment = { horizontal: 'center', vertical: 'middle' }
  sheet.getRow(row).height = 22
  row++

  sheet.getRow(row).height = 8
  row++

  const metaRows: [string, string][] = [
    ['Generated Date', genDate],
    ['Generated Time', genTime],
    ['Generated By', genBy],
    ['Applied Filters', filterString],
  ]
  for (const [label, value] of metaRows) {
    sheet.getCell(row, 1).value = label
    sheet.getCell(row, 1).font = { name: 'Segoe UI', size: 9, bold: true, color: { argb: 'FF475569' } }
    sheet.mergeCells(row, 2, row, colCount)
    sheet.getCell(row, 2).value = value
    sheet.getCell(row, 2).font = { name: 'Segoe UI', size: 9, color: { argb: 'FF334155' } }
    sheet.getCell(row, 2).alignment = { wrapText: true, vertical: 'middle' }
    sheet.getRow(row).height = 18
    row++
  }

  sheet.getRow(row).height = 10
  row++

  const headerRowIndex = row
  ACTIVE_DIRECTORY_EXPORT_HEADERS.forEach((h, idx) => {
    const cell = sheet.getCell(row, idx + 1)
    cell.value = h.label
    cell.font = { name: 'Segoe UI', size: 10, bold: true, color: { argb: 'FFFFFFFF' } }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_GREEN_ARGB } }
    cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true }
    cell.border = {
      top: { style: 'medium', color: { argb: 'FF048F26' } },
      bottom: { style: 'medium', color: { argb: 'FF048F26' } },
      left: borderThin.left,
      right: borderThin.right,
    }
  })
  sheet.getRow(row).height = 24
  row++

  data.forEach((record, dataIdx) => {
    const cells = mapRowToCells(record)
    const isEven = dataIdx % 2 === 0
    const fillArgb = isEven ? 'FFFFFFFF' : 'FFF0FDF4'
    cells.forEach((val, colIdx) => {
      const cell = sheet.getCell(row, colIdx + 1)
      cell.value = val
      cell.font = { name: 'Segoe UI', size: 9, color: { argb: 'FF1E293B' } }
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: fillArgb } }
      cell.alignment = {
        horizontal: colIdx <= 4 ? 'left' : 'center',
        vertical: 'middle',
        wrapText: colIdx === 3 || colIdx === 4,
      }
      cell.border = borderThin
    })
    sheet.getRow(row).height = 20
    row++
  })

  sheet.getRow(row).height = 12
  row++

  sheet.mergeCells(row, 1, row, colCount)
  sheet.getCell(row, 1).value = `Total Employees Exported: ${data.length}`
  sheet.getCell(row, 1).font = { name: 'Segoe UI', size: 9, bold: true, color: { argb: 'FF1E293B' } }
  row++

  sheet.mergeCells(row, 1, row, colCount)
  sheet.getCell(row, 1).value = `Generated on ${genDate} ${genTime}`
  sheet.getCell(row, 1).font = { name: 'Segoe UI', size: 9, color: { argb: 'FF64748B' } }
  row++

  sheet.mergeCells(row, 1, row, colCount)
  sheet.getCell(row, 1).value = `${COMPANY_NAME} – Confidential Document`
  sheet.getCell(row, 1).font = { name: 'Segoe UI', size: 9, bold: true, italic: true, color: { argb: 'FF475569' } }

  ACTIVE_DIRECTORY_EXPORT_HEADERS.forEach((h, idx) => {
    const wch = EXCEL_COL_WIDTHS[h.key as string] ?? 18
    sheet.getColumn(idx + 1).width = wch
  })

  sheet.views = [
    {
      state: 'frozen',
      ySplit: headerRowIndex,
      showGridLines: true,
    },
  ]
  sheet.autoFilter = {
    from: { row: headerRowIndex, column: 1 },
    to: { row: headerRowIndex + data.length, column: colCount },
  }

  const buffer = await workbook.xlsx.writeBuffer()
  downloadExcelBuffer(buffer, `${filename}.xlsx`)
}
