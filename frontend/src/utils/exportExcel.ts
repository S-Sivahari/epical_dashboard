import * as XLSX from 'xlsx'

export interface ExportExcelOptions {
  generatedBy?: string
  filters?: Record<string, string | undefined>
  panelTitle?: string
  reportTitle?: string
  sheetName?: string
}

function formatDateStr(d: string | Date | undefined | null): string {
  if (!d) return '—'
  const date = new Date(d)
  if (isNaN(date.getTime())) return String(d)
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  return `${String(date.getDate()).padStart(2, '0')}-${months[date.getMonth()]}-${date.getFullYear()}`
}

/**
 * Exports data to an Excel (.xlsx) file with professional formatting.
 */
export function exportToExcel<T extends Record<string, any>>(
  data: T[],
  filename: string,
  headers: { key: keyof T | string; label: string }[],
  options?: ExportExcelOptions,
) {
  if (!data.length) return

  const now = new Date()
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  const genDate = `${String(now.getDate()).padStart(2, '0')}-${months[now.getMonth()]}-${now.getFullYear()}`

  let hours = now.getHours()
  const minutes = String(now.getMinutes()).padStart(2, '0')
  const ampm = hours >= 12 ? 'PM' : 'AM'
  hours = hours % 12
  hours = hours ? hours : 12
  const genTime = `${String(hours).padStart(2, '0')}:${minutes} ${ampm}`
  const genBy = options?.generatedBy || 'Admin'

  const filterParts: string[] = []
  if (options?.filters) {
    Object.entries(options.filters).forEach(([key, val]) => {
      if (val && val !== 'all' && val !== '') {
        let displayKey = key
        if (key === 'employeeId') displayKey = 'Employee ID'
        else if (key === 'employmentType') displayKey = 'Type'
        else displayKey = key.charAt(0).toUpperCase() + key.slice(1)

        filterParts.push(`${displayKey} = ${val}`)
      }
    })
  }
  const filterString = filterParts.length > 0 ? filterParts.join(' | ') : 'None'

  const aoa: unknown[][] = []

  aoa.push(['------------------------------------------------------------'])
  aoa.push(['                    EPICAL LAYOUTS PVT LTD'])
  aoa.push([`                 ${options?.panelTitle ?? 'Document Management Panel'}`])
  aoa.push([`                    ${options?.reportTitle ?? 'Employee Details Report'}`])
  aoa.push(['                         [ Excel · .xlsx ]'])
  aoa.push(['------------------------------------------------------------'])
  aoa.push([])
  aoa.push([`Generated Date : ${genDate}`])
  aoa.push([`Generated Time : ${genTime}`])
  aoa.push([`Generated By   : ${genBy}`])
  aoa.push([])
  aoa.push(['Applied Filters:'])
  aoa.push([filterString])
  aoa.push([])
  aoa.push(['------------------------------------------------------------'])
  aoa.push([])

  aoa.push(headers.map((h) => h.label))

  data.forEach((row) => {
    aoa.push(
      headers.map((h) => {
        let value: unknown = row[h.key]
        if (h.key === 'joinedAt' || h.key === 'dob') {
          value = formatDateStr(value as string)
        } else if (h.key === 'pfEsi') {
          value = value === 'on' ? 'Enabled' : value === 'off' ? 'Disabled' : '—'
        } else if (h.key === 'ctc' && typeof value === 'number') {
          value = `₹${value.toLocaleString('en-IN')}`
        }
        return value === null || value === undefined ? '—' : String(value)
      }),
    )
  })

  aoa.push([])
  aoa.push(['------------------------------------------------------------'])
  aoa.push(['EPICAL LAYOUTS PVT LTD – Confidential Document'])
  aoa.push([`System Generated Report | Generated on ${genDate} ${genTime}`])
  aoa.push(['------------------------------------------------------------'])

  const worksheet = XLSX.utils.aoa_to_sheet(aoa)

  worksheet['!cols'] = headers.map((h) => {
    if (h.key === 'email' || h.key === 'personalEmail') return { wch: 30 }
    if (h.key === 'employeeId') return { wch: 15 }
    if (h.key === 'address') return { wch: 40 }
    return { wch: 20 }
  })

  const workbook = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(workbook, worksheet, options?.sheetName ?? 'Employees')

  XLSX.writeFile(workbook, `${filename}.xlsx`)
}
