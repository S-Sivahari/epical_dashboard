import ExcelJS from 'exceljs'
import {
  downloadExcelBuffer,
  EXCEL_LOGO_MAX_WIDTH,
  fetchExportLogo,
  scaleExportLogo,
} from '@/utils/exportLogo'

export interface ExportExcelOptions {
  generatedBy?: string
  filters?: Record<string, string | undefined>
  panelTitle?: string
  reportTitle?: string
  sheetName?: string
}

function formatDateStr(d: string | Date | undefined | null): string {
  if (!d) return '—'
  const date = new Date(d)
  if (isNaN(date.getTime())) return String(d)
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  return `${String(date.getDate()).padStart(2, '0')}-${months[date.getMonth()]}-${date.getFullYear()}`
}

function addLogoToSheet(workbook: ExcelJS.Workbook, sheet: ExcelJS.Worksheet, logo: Awaited<ReturnType<typeof fetchExportLogo>>) {
  if (!logo) return 1

  const imageId = workbook.addImage({
    buffer: logo.buffer,
    extension: 'png',
  })
  const { width, height } = scaleExportLogo(logo.width, logo.height, EXCEL_LOGO_MAX_WIDTH)
  const logoRows = Math.max(3, Math.ceil(height / 18))

  for (let i = 1; i <= logoRows; i++) {
    sheet.getRow(i).height = 20
  }

  sheet.addImage(imageId, {
    tl: { col: 0.2, row: 0.2 },
    ext: { width, height },
  })

  return logoRows + 1
}

/**
 * Exports data to an Excel (.xlsx) file with professional formatting and company logo.
 */
export async function exportToExcel<T extends Record<string, any>>(
  data: T[],
  filename: string,
  headers: { key: keyof T; label: string }[],
  options?: ExportExcelOptions,
) {
  if (!data.length) return

  const logo = await fetchExportLogo()
  const now = new Date()
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  const genDate = `${String(now.getDate()).padStart(2, '0')}-${months[now.getMonth()]}-${now.getFullYear()}`

  let hours = now.getHours()
  const minutes = String(now.getMinutes()).padStart(2, '0')
  const ampm = hours >= 12 ? 'PM' : 'AM'
  hours = hours % 12
  hours = hours ? hours : 12
  const genTime = `${String(hours).padStart(2, '0')}:${minutes} ${ampm}`
  const genBy = options?.generatedBy || 'Admin'

  const filterParts: string[] = []
  if (options?.filters) {
    Object.entries(options.filters).forEach(([key, val]) => {
      if (val && val !== 'all' && val !== '') {
        let displayKey = key
        if (key === 'employeeId') displayKey = 'Employee ID'
        else if (key === 'employmentType') displayKey = 'Type'
        else displayKey = key.charAt(0).toUpperCase() + key.slice(1)

        filterParts.push(`${displayKey} = ${val}`)
      }
    })
  }
  const filterString = filterParts.length > 0 ? filterParts.join(' | ') : 'None'

  const workbook = new ExcelJS.Workbook()
  const sheet = workbook.addWorksheet(options?.sheetName ?? 'Employees')
  let row = addLogoToSheet(workbook, sheet, logo)

  const addRow = (values: (string | number)[]) => {
    sheet.getRow(row).values = values
    row += 1
  }

  addRow(['------------------------------------------------------------'])
  addRow(['                    EPICAL LAYOUTS PVT LTD'])
  addRow([`                 ${options?.panelTitle ?? 'Document Management Panel'}`])
  addRow([`                    ${options?.reportTitle ?? 'Employee Details Report'}`])
  addRow(['                         [ Excel · .xlsx ]'])
  addRow(['------------------------------------------------------------'])
  addRow([])
  addRow([`Generated Date : ${genDate}`])
  addRow([`Generated Time : ${genTime}`])
  addRow([`Generated By   : ${genBy}`])
  addRow([])
  addRow(['Applied Filters:'])
  addRow([filterString])
  addRow([])
  addRow(['------------------------------------------------------------'])
  addRow([])

  const headerRow = row
  sheet.getRow(row).values = headers.map((h) => h.label)
  sheet.getRow(row).font = { bold: true }
  row += 1

  data.forEach((item) => {
    sheet.getRow(row).values = headers.map((h) => {
      let value: any = item[h.key]
      if (h.key === 'joinedAt' || h.key === 'dob') {
        value = formatDateStr(value)
      } else if (h.key === 'pfEsi') {
        value = value === 'on' ? 'Enabled' : value === 'off' ? 'Disabled' : '—'
      } else if (h.key === 'ctc' && typeof value === 'number') {
        value = `₹${value.toLocaleString('en-IN')}`
      }
      return value === null || value === undefined ? '—' : String(value)
    })
    row += 1
  })

  addRow([])
  addRow(['------------------------------------------------------------'])
  addRow(['EPICAL LAYOUTS PVT LTD – Confidential Document'])
  addRow([`System Generated Report | Generated on ${genDate} ${genTime}`])
  addRow(['------------------------------------------------------------'])

  sheet.columns = headers.map((h) => {
    if (h.key === 'email' || h.key === 'personalEmail') return { width: 30 }
    if (h.key === 'employeeId') return { width: 15 }
    if (h.key === 'address') return { width: 40 }
    return { width: 20 }
  })

  sheet.getRow(headerRow).eachCell((cell) => {
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF1E293B' },
    }
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } }
  })

  const buffer = await workbook.xlsx.writeBuffer()
  downloadExcelBuffer(buffer, `${filename}.xlsx`)
}
